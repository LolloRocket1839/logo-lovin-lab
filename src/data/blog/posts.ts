export const getRelatedPosts = (currentSlug: string, category: string, currentTags: string[] = [], lang: 'it' | 'en' = 'it', limit: number = 3): BlogPost[] => {
  // Calculate relevance score based on category and shared tags
  const scoredPosts = blogPosts
    .filter(post => post.slug !== currentSlug)
    .map(post => {
      let score = 0;
      
      // Same category = +10 points
      if (post.category === category) {
        score += 10;
      }
      
      // Shared tags = +2 points each
      const postTags = post.translations?.[lang]?.tags || post.translations?.it?.tags || [];
      const sharedTags = currentTags.filter(tag => 
        postTags.some(postTag => postTag.toLowerCase() === tag.toLowerCase())
      );
      score += sharedTags.length * 2;
      
      return { post, score, sharedTags: sharedTags.length };
    })
    .filter(item => item.score > 0) // Only include posts with some relevance
    .sort((a, b) => {
      // Sort by score first, then by date (most recent)
      if (b.score !== a.score) return b.score - a.score;
      return new Date(b.post.date).getTime() - new Date(a.post.date).getTime();
    });
  
  return scoredPosts.slice(0, limit).map(item => item.post);
};

export const searchPosts = (posts: BlogPost[], searchQuery: string, lang: 'it' | 'en' = 'it'): BlogPost[] => {
  if (!searchQuery.trim()) return posts;
  
  const query = searchQuery.toLowerCase().trim();
  
  return posts.filter(post => {
    const translation = post.translations?.[lang] || post.translations?.it;
    if (!translation) return false;
    
    const titleMatch = translation.title?.toLowerCase().includes(query) || false;
    const excerptMatch = translation.excerpt?.toLowerCase().includes(query) || false;
    const tagsMatch = translation.tags?.some(tag => tag.toLowerCase().includes(query)) || false;
    const keywordsMatch = translation.seo?.keywords?.some(keyword => 
      keyword.toLowerCase().includes(query)
    ) || false;
    
    return titleMatch || excerptMatch || tagsMatch || keywordsMatch;
  });
};

export const getAllTags = (lang: 'it' | 'en' = 'it'): string[] => {
  const tagsSet = new Set<string>();
  
  blogPosts.forEach(post => {
    const translation = post.translations?.[lang] || post.translations?.it;
    if (translation?.tags) {
      translation.tags.forEach(tag => tagsSet.add(tag));
    }
  });
  
  return Array.from(tagsSet).sort();
};

export const filterPostsByTags = (posts: BlogPost[], selectedTags: string[], lang: 'it' | 'en' = 'it'): BlogPost[] => {
  if (selectedTags.length === 0) return posts;
  
  return posts.filter(post => {
    const translation = post.translations?.[lang] || post.translations?.it;
    if (!translation?.tags) return false;
    
    return selectedTags.some(selectedTag => 
      translation.tags.includes(selectedTag)
    );
  });
};
